type Row = [
  id: string,
  name: string,
  aliases: string,
  faction: string,
  category: string,
  targets: string,
  stage: string,
  role: string,
  strong: string,
  caution: string,
  tip: string,
  counters: [string, string][],
];
function group(game: GameId, rows: Row[]): Unit[] {
  return rows.map(
    ([
      id,
      name,
      aliases,
      faction,
      category,
      targets,
      stage,
      role,
      strong,
      caution,
      tip,
      counters,
    ]) => ({
      game,
      id,
      name,
      aliases,
      faction,
      category,
      targets,
      stage,
      role,
      strong,
      caution,
      tip,
      counters: counters.map(([id, reason]) => ({ id, reason })),
    }),
  );
}

